"""uninstall: undo what host-setup recorded in its journal, newest change
first, so the host is as it was before glovebox.

Only what the journal holds is touched. A file edited since glovebox wrote
it is shown as a diff and changed only if you say so; the packages are a
separate question. Whatever isn't undone stays in the journal, so a later
uninstall offers it again. The journal goes once it's empty.
"""

import shutil

from . import journal
from .common import capture, die, glovebox_users, log, read_root, root_exists
from .hostsetup import (Plan, Step, ask, confirm, execute, short_diff,
                        start_log)
from .journal import JOURNAL, STAMP, STATE_DIR, describe, sha256


# Units other things on the host may rely on by now: asked about, like the
# packages, instead of being put back without a question.
SHARED_UNITS = ("libvirtd.service",)


def libvirt_vms():
    """(glovebox's VMs, the other libvirt VMs)."""
    if not shutil.which("virsh"):
        return [], []
    if capture(["sudo", "virsh", "list", "--all"]).returncode != 0:
        die("libvirt isn't reachable, so uninstall can't check that no "
            "sandbox VMs are left. Start it (sudo systemctl start "
            "libvirtd) and run uninstall again.")
    from .vms import domain_states
    ours, others = [], []
    for name in sorted(domain_states()):
        (ours if glovebox_users(name) is not None else others).append(name)
    return ours, others


class Undo:
    def __init__(self, a, other_vms=()):
        self.a = a
        self.other_vms = list(other_vms)
        self.plan = Plan([])
        self.steps, self.notes = self.plan.section(
            "uninstall: undo host-setup's changes, newest first")
        self.kept = []    # entries left in the journal
        self.forget = []  # entries with nothing left to undo
        self.reload = False

    def step(self, what, cmds, entries, diff=None):
        ids = [e["id"] for e in entries]
        self.steps.append(Step(what, cmds, diff,
                               done=lambda: journal.forget(ids)))

    def keep(self, entries, why):
        self.kept.extend(entries)
        self.notes.append(why)

    def question(self, prompt):
        # Asked while planning, so the plan shown is the one that runs.
        if self.a.dry_run:
            return True
        return ask(prompt)

    # --- one method per entry type ------------------------------------------------

    def file(self, group):
        path = group[-1]["path"]
        original = group[0].get("backup")   # None: glovebox created it
        expected = group[-1].get("sha256")  # None: generated, not checked
        if path.startswith("/etc/systemd/"):
            self.reload = True
        if original is None and expected is None:
            # Generated by glovebox (the CA, the cloud image cache): nothing
            # to compare or restore, and it may be large or binary.
            if root_exists(path):
                self.step(f"Remove {path}, which glovebox created.",
                          [["sudo", "rm", "-f", path]], group)
            else:
                self.forget.extend(group)
            return
        current = read_root(path)
        before = read_root(original) if original else None
        if original and before is None:
            die(f"The saved original of {path}, {original}, is missing; "
                f"restore it by hand or remove its lines from {JOURNAL}.")
        if current is None:
            if original:
                self.step(f"Restore {path} (missing now) as it was before "
                          f"glovebox.", [["sudo", "cp", "-p", original, path]],
                          group)
            else:
                self.forget.extend(group)
            return
        action = (f"Restore {path} as it was before glovebox" if original
                  else f"Remove {path}, which glovebox created")
        cmds = ([["sudo", "cp", "-p", original, path]] if original
                else [["sudo", "rm", "-f", path]])
        diff = short_diff(current, before or "", path,
                          "after uninstall" if original else "(removed)")
        if expected and sha256(current) != expected:
            saved = f"{path}.glovebox-uninstall-{STAMP}"
            print(f"\n{path} was edited after glovebox wrote it. Uninstall "
                  f"would change it like this:")
            for line in diff.splitlines():
                print(f"  | {line}")
            if self.a.dry_run:
                self.notes.append(f"{path} was edited since; the real run "
                                  f"asks before touching it.")
            if not self.question(f"{action} anyway (your version is kept as "
                                 f"{saved})?"):
                self.keep(group, f"{path} was edited since and is kept as "
                                 f"is; it stays in the journal.")
                return
            cmds = [["sudo", "cp", "-p", path, saved]] + cmds
            action += f"; your edited version is kept as {saved}"
        self.step(action + ".", cmds, group,
                  diff if original else None)

    def dir(self, e):
        path = e["path"]
        if not root_exists(path):
            self.forget.append(e)
        elif any(k.get("path", "").startswith(path + "/") for k in self.kept):
            # What's inside was created after it, so it was decided first.
            self.keep([e], f"{path} holds something kept, so it stays too.")
        elif e.get("tree"):
            self.step(f"Remove {path} and its contents (glovebox created it).",
                      [["sudo", "rm", "-rf", "--one-file-system", path]], [e])
        else:
            def done():
                journal.forget([e["id"]])
                if root_exists(path):
                    log(f"{path} is not empty (something else was put in "
                        f"it since), so it is kept.")
            self.steps.append(Step(
                f"Remove the directory {path} if it's empty (glovebox "
                f"created it).",
                [["sudo", "rmdir", "--ignore-fail-on-non-empty", path]],
                done=done))

    def service(self, e):
        unit = e["unit"]
        state = capture(["systemctl", "show", "-p", "LoadState", "--value",
                         unit]).stdout.strip()
        cmds = []
        if state not in ("", "not-found"):
            if not e["was_active"]:
                cmds.append(["sudo", "systemctl", "stop", unit])
            if not e["was_enabled"]:
                cmds.append(["sudo", "systemctl", "disable", unit])
        if not cmds:
            self.forget.append(e)
            return
        if unit in SHARED_UNITS:
            print(f"\nhost-setup started {unit} (before, it was "
                  f"{'enabled' if e['was_enabled'] else 'disabled'} and "
                  f"{'running' if e['was_active'] else 'stopped'}).")
            if self.other_vms:
                print(f"Other libvirt VMs on this host need it: "
                      f"{', '.join(self.other_vms)}")
            if self.a.dry_run:
                self.notes.append(f"The real run asks whether to put {unit} "
                                  f"back.")
            if not self.question(f"Put {unit} back as it was? Say no if you "
                                 f"use libvirt for other VMs"):
                self.keep([e], f"{unit} is kept as it is; it stays in the "
                               f"journal.")
                return
        self.reload = True
        self.step(f"Put {unit} back as it was: "
                  f"{'enabled' if e['was_enabled'] else 'disabled'}, "
                  f"{'running' if e['was_active'] else 'stopped'}.", cmds, [e])

    def sysctl(self, e):
        key, previous = e["key"], e["previous"]
        with open("/proc/sys/" + key.replace(".", "/")) as f:
            current = f.read().strip()
        if current == previous:
            self.forget.append(e)
            return
        self.step(f"Set {key} back to {previous}, as before glovebox. "
                  f"Anything else on this host that needs it (Docker, "
                  f"other VMs) sets it again itself when it starts.",
                  [["sudo", "sysctl", "-w", f"{key}={previous}"]], [e])

    def libvirt_net(self, e):
        name = e["name"]
        state = journal.libvirt_net_state(name)
        if state is None:
            self.forget.append(e)
            return
        autostart, active = state
        cmds = []
        if not e["was_defined"]:
            if active:
                cmds.append(["sudo", "virsh", "net-destroy", name])
            cmds.append(["sudo", "virsh", "net-undefine", name])
            what = f"Remove the libvirt network {name}, which glovebox defined."
        else:
            if autostart and not e["was_autostart"]:
                cmds.append(["sudo", "virsh", "net-autostart", "--disable",
                             name])
            if active and not e["was_active"]:
                cmds.append(["sudo", "virsh", "net-destroy", name])
            what = f"Put the libvirt network {name} back as it was."
        if cmds:
            self.step(what, cmds, [e])
        else:
            self.forget.append(e)

    def nft_tables(self, e):
        present = [t for t in e["tables"] if capture(
            ["sudo", "nft", "list", "table", *t]).returncode == 0]
        if not present:
            self.forget.append(e)
            return
        self.step("Delete glovebox's nftables tables "
                  f"({', '.join(' '.join(t) for t in present)}). No VM runs, "
                  f"so nothing relies on them.",
                  [["sudo", "nft", "delete", "table", *t] for t in present],
                  [e])

    def ufw_rule(self, e):
        rule = e["rule"]
        # A route rule is deleted with `ufw route delete ...`; `ufw delete
        # route ...` is a syntax error.
        cmd = (["sudo", "ufw", "route", "delete", *rule[1:]]
               if rule[0] == "route" else ["sudo", "ufw", "delete", *rule])
        self.step(f"Delete the UFW rule glovebox added: ufw "
                  f"{' '.join(rule)}.", [cmd], [e])

    def packages(self, entries):
        by_pm = {}
        for e in entries:
            by_pm.setdefault(e["pm"], set()).update(e["names"])
        for pm, names in by_pm.items():
            names = sorted(names & journal.installed_packages(pm))
            ours = [e for e in entries if e["pm"] == pm]
            if not names:
                self.forget.extend(ours)
                continue
            extra = []
            if pm == "apt":
                sim = capture(["apt-get", "-s", "purge", *names]).stdout
                plain = {n.split(":")[0] for n in names}
                extra = sorted({ln.split()[1].split(":")[0]
                                for ln in sim.splitlines()
                                if ln.startswith("Purg ")} - plain)
                cmds = [["sudo", "env", "DEBIAN_FRONTEND=noninteractive",
                         "apt-get", "purge", "-y", *names]]
            else:
                # Without -c pacman refuses when other packages depend on
                # these, instead of removing those too.
                cmds = [["sudo", "pacman", "-Rn", "--noconfirm", *names]]
            print(f"\nhost-setup installed these packages (with their "
                  f"dependencies): {' '.join(names)}")
            if extra:
                print(f"Packages installed since depend on them and would "
                      f"be removed too: {' '.join(extra)}")
            if self.other_vms:
                print(f"Other libvirt VMs on this host may need them: "
                      f"{', '.join(self.other_vms)}")
            if self.a.dry_run:
                self.notes.append("The real run asks separately whether to "
                                  "remove the packages.")
            if not self.question("Remove these packages too? You may use "
                                 "them for other things now"):
                self.keep(ours, f"The packages are kept: {' '.join(names)}. "
                                f"They stay in the journal.")
                continue
            self.step(f"Remove the packages host-setup installed: "
                      f"{' '.join(names)}"
                      + (f", and {' '.join(extra)}, which depend on them"
                         if extra else "") + ".", cmds, ours)


def cmd_uninstall(a):
    start_log("uninstall")
    entries = journal.read()
    if not entries:
        log(f"{JOURNAL} records no changes: there is nothing to undo.")
        return
    vms, other_vms = libvirt_vms()
    if vms:
        die(f"Sandbox VMs still exist: {', '.join(vms)}. Delete them "
            f"first (./glovebox delete <name>), or keep them and don't "
            f"uninstall.")
    log(f"{len(entries)} change(s) recorded in {JOURNAL}:")
    for e in entries:
        print(f"  {e['time']}  {describe(e)}")

    u = Undo(a, other_vms)
    files, packages = {}, []
    for e in entries:
        if e["type"] == "file":
            files.setdefault(e["path"], []).append(e)
    done_files = set()
    for e in reversed(entries):
        t = e["type"]
        if t == "packages":
            packages.append(e)  # last: everything else uses them
        elif t == "file":
            if e["path"] not in done_files:
                done_files.add(e["path"])
                u.file(files[e["path"]])
        elif hasattr(u, t):
            getattr(u, t)(e)
        else:
            u.keep([e], f"Unknown journal entry type {t!r}; left as is.")
    if u.reload:
        u.steps.append(Step("Reload systemd, so the removed units are gone.",
                            [["sudo", "systemctl", "daemon-reload"]]))
    u.packages(list(reversed(packages)))

    if u.forget:
        ids = [e["id"] for e in u.forget]
        u.notes.append(f"{len(ids)} change(s) are already undone (or gone); "
                       f"they are dropped from the journal.")
        u.steps.insert(0, Step("Drop the changes that are already undone "
                               "from the journal.", [],
                               done=lambda: journal.forget(ids)))
    if u.kept:
        u.notes.append(f"{len(u.kept)} change(s) stay in {JOURNAL}; run "
                       f"uninstall again to undo them later.")
    else:
        u.steps.append(Step(f"Remove {STATE_DIR}: the journal and the saved "
                            f"originals, now that everything is undone.",
                            [["sudo", "rm", "-rf", STATE_DIR]]))
    if not confirm(u.plan, a):
        return
    execute(u.plan)
    if not u.kept:
        log("glovebox's host changes are undone. The repo and its logs/ "
            "are yours to delete.")
